/// Scales a standard JPEG quantization table for [quality].
List<int> jpegScaledQuantTable(List<int> table, int quality) {
  if (quality < 1 || quality > 100) {
    throw ArgumentError.value(quality, 'quality');
  }
  final scale = quality < 50 ? 5000 ~/ quality : 200 - quality * 2;
  return <int>[
    for (final value in table)
      ((value * scale + 50) ~/ 100).clamp(1, 255).toInt(),
  ];
}

